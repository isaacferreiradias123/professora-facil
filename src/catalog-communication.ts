const arts: ClassroomItem[] = artRows.map(
  ([id, title, body, callout, composition], i) => {
    const [background, foreground] = [
      ['#f9f1e3', '#194c40'],
      ['#efe6f5', '#442653'],
      ['#f5e5d9', '#5a3221'],
    ][i % 3]
    const visual: Values = {
      title,
      body,
      callout,
      composition,
      background,
      foreground,
      font: 'Georgia',
      format: composition === 'aviso' ? 'Vertical 4:5' : 'Quadrado 1:1',
      model: String(i % 3),
    }
    return {
      id: 'arte-caderno-' + id,
      title,
      tool: 'postagem',
      category: org,
      description: body,
      visual,
    }
  },
)
